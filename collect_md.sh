#!/bin/bash
#
# Скрипт собирает содержимое всех .md файлов из заданной папки и её подпапок
# в один txt-файл. Перед содержимым каждого файла выводится заголовок вида:
#   === имя подпапки (если есть) / имя файла.md ===
#
# Использование:
#   ./collect_md.sh <папка_с_исходниками> <выходной_файл.txt>

set -euo pipefail

# ---- Проверка аргументов ----
if [ $# -ne 2 ]; then
    echo "Использование: $0 <папка_с_исходниками> <выходной_файл.txt>" >&2
    exit 1
fi

SRC_DIR="$1"
OUT_FILE="$2"

if [ ! -d "$SRC_DIR" ]; then
    echo "Ошибка: '$SRC_DIR' — не папка или не существует." >&2
    exit 1
fi

# Очищаем (или создаём) выходной файл
: > "$OUT_FILE"

# ---- Обход .md файлов ----
# -print0 / read -d '' — чтобы корректно работать с пробелами и спецсимволами в путях
found=0
while IFS= read -r -d '' file; do
    # Путь относительно исходной папки (без ведущего ./)
    rel_path="${file#"$SRC_DIR"/}"

    # Разделитель
    {
        printf '\n=== %s ===\n\n' "$rel_path"
        cat "$file"
        printf '\n'
    } >> "$OUT_FILE"

    found=$((found + 1))
done < <(find "$SRC_DIR" -type f -name '*.md' -print0 | sort -z)

echo "Готово. Обработано файлов: $found"
echo "Результат: $OUT_FILE"
